/**
 * Builds and checks Journey pack 2 (levels 61–150), frozen and verified like the launch pack.
 *
 *   npm run pack:build   → regenerates src/data/journeyPack2.ts (and the launch pack)
 *   npm run pack:check   → regenerates in memory and fails if the committed pack differs or any board fails
 *
 *  - Levels 61–70 are spec 1: exactly the boards the original ladder already gave players (8×8).
 *  - Levels 71–150 are spec 2: the rotated 5×5–8×8 ladder, each board chosen by its measured difficulty.
 * Every board must have n connected regions, satisfy the rules, have exactly one solution (exact solver), be solvable
 * by the human deduction engine with no guessing, be at most 8×8, and carry the label its measurement gives it.
 */

import { writeFileSync } from 'node:fs';
import { generatePuzzle } from '../src/engine/generator';
import { levelSpec } from '../src/engine/levels';
import { encodeBoard, verifyBoard, type PackFile2, type PackLevel2 } from '../src/data/packFormat';
import { GRADING_VERSION, profileOf } from '../src/game/grading';
import { JOURNEY_V2_FROM, MAX_NEW_BOARD_SIZE, journeyTargetV2, pickBoard } from '../src/game/specs';
import { JOURNEY_PACK_FIRST, JOURNEY_PACK_LAST } from '../src/data/journeyPackRange';
import type { Puzzle } from '../src/engine/types';

const write = process.argv.includes('--write');

function buildLevel(level: number): { enc: PackLevel2; puzzle: Puzzle } {
  let puzzle: Puzzle;
  let spec: 1 | 2;
  let target: PackLevel2['target'];
  if (level < JOURNEY_V2_FROM) {
    const s = levelSpec(level);
    puzzle = generatePuzzle({ size: s.size, seed: s.seed, difficulty: s.difficulty });
    spec = 1;
  } else {
    const t = journeyTargetV2(level);
    puzzle = pickBoard(t);
    spec = 2;
    target = t.tier;
  }
  const prof = profileOf(puzzle);
  return { enc: { ...encodeBoard(level, puzzle), spec, ...(target ? { target } : {}), tier: prof.tier, score: prof.score }, puzzle };
}

const levels: PackLevel2[] = [];
let failures = 0;
for (let level = JOURNEY_PACK_FIRST; level <= JOURNEY_PACK_LAST; level++) {
  const { enc, puzzle } = buildLevel(level);
  const problems = verifyBoard(puzzle);
  if (puzzle.size > MAX_NEW_BOARD_SIZE) problems.push(`size ${puzzle.size} exceeds ${MAX_NEW_BOARD_SIZE}`);
  if (enc.target && enc.target !== enc.tier) problems.push(`asked for ${enc.target}, measured ${enc.tier}`);
  if (problems.length) {
    failures++;
    console.error(`level ${level}: ${problems.join('; ')}`);
  }
  levels.push(enc);
}
if (failures) {
  console.error(`${failures} level(s) failed verification`);
  process.exit(1);
}

const pack: PackFile2 = { v: 2, generatorVersion: 1, gradingVersion: GRADING_VERSION, levels };
const lines = levels.map((l) => `    ${JSON.stringify(l)},`).join('\n');
const out = `/**
 * Journey pack 2: levels ${JOURNEY_PACK_FIRST}–${JOURNEY_PACK_LAST}, frozen and verified. GENERATED by scripts/build-journey-pack.ts — do not edit.
 * Levels ${JOURNEY_PACK_FIRST}–${JOURNEY_V2_FROM - 1} are the original (spec 1) boards; ${JOURNEY_V2_FROM}+ are the rotated 5×5–8×8 ladder (spec 2), each
 * picked and labeled by measured difficulty (grading v${GRADING_VERSION}). Same encoding as the launch pack plus spec / target / tier / score.
 */

import type { PackFile2 } from './packFormat';

export const JOURNEY_PACK_2: PackFile2 = {
  v: 2,
  generatorVersion: ${pack.generatorVersion},
  gradingVersion: ${pack.gradingVersion},
  levels: [
${lines}
  ],
};
`;

const path = new URL('../src/data/journeyPack2.ts', import.meta.url);
if (write) {
  writeFileSync(path, out);
  console.log(`wrote src/data/journeyPack2.ts (${levels.length} levels, ${out.length} bytes)`);
} else {
  const { JOURNEY_PACK_2 } = await import('../src/data/journeyPack2');
  const same = JSON.stringify(JOURNEY_PACK_2) === JSON.stringify(pack);
  if (!same) {
    console.error('src/data/journeyPack2.ts differs from what the generator + grader produce now. A shipped level would change.');
    process.exit(1);
  }
  console.log(`${levels.length} pack-2 levels verified and identical to the committed pack`);
}
const bySize = new Map<string, number>();
for (const l of levels) bySize.set(`${l.size}×${l.size} ${l.tier}`, (bySize.get(`${l.size}×${l.size} ${l.tier}`) ?? 0) + 1);
console.log('mix:', [...bySize].sort().map(([s, c]) => `${s}: ${c}`).join(', '));
