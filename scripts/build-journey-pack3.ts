/**
 * Builds and checks Journey pack 3 (levels 6–150 on spec 3, the steeper ramp of D31), frozen and verified like the
 * other packs.
 *
 *   npm run pack:build   → regenerates src/data/journeyPack3.ts (with the other packs)
 *   npm run pack:check   → regenerates in memory and fails if the committed pack differs or any board fails
 *
 * Every board must have n connected regions, satisfy the rules, have exactly one solution (exact solver), be solvable
 * by the human deduction engine with no guessing, be at most 9×9, and measure exactly the difficulty its slot asks for.
 */

import { writeFileSync } from 'node:fs';
import { encodeBoard, verifyBoard, type PackFile2, type PackLevel2 } from '../src/data/packFormat';
import { GRADING_VERSION, profileOf } from '../src/game/grading';
import { JOURNEY_V3_FROM, MAX_JOURNEY_SIZE, journeyTargetV3, pickBoard } from '../src/game/specs';
import { JOURNEY_PACK3_LAST } from '../src/data/journeyPackRange';

const write = process.argv.includes('--write');

const levels: PackLevel2[] = [];
let failures = 0;
for (let level = JOURNEY_V3_FROM; level <= JOURNEY_PACK3_LAST; level++) {
  const t = journeyTargetV3(level);
  const puzzle = pickBoard(t);
  const prof = profileOf(puzzle);
  const enc: PackLevel2 = { ...encodeBoard(level, puzzle), spec: 3, target: t.tier, tier: prof.tier, score: prof.score };
  const problems = verifyBoard(puzzle);
  if (puzzle.size !== t.size) problems.push(`size ${puzzle.size}, slot asks ${t.size}`);
  if (puzzle.size > MAX_JOURNEY_SIZE) problems.push(`size ${puzzle.size} exceeds ${MAX_JOURNEY_SIZE}`);
  if (enc.target !== enc.tier) problems.push(`asked for ${enc.target}, measured ${enc.tier}`);
  if (problems.length) {
    failures++;
    console.error(`level ${level}: ${problems.join('; ')}`);
  }
  levels.push(enc);
}
if (failures) {
  console.error(`${failures} level(s) failed verification`);
  process.exit(1);
}

const pack: PackFile2 = { v: 2, generatorVersion: 1, gradingVersion: GRADING_VERSION, levels };
const lines = levels.map((l) => `    ${JSON.stringify(l)},`).join('\n');
const out = `/**
 * Journey pack 3: levels ${JOURNEY_V3_FROM}–${JOURNEY_PACK3_LAST} on spec 3 (the steeper ramp, D31), frozen and verified. GENERATED by
 * scripts/build-journey-pack3.ts — do not edit. 7×7 from level 6, 8×8 joining from 15, 9×9 from 40 and the main size
 * after 70, with smaller breather boards; each picked and labeled by measured difficulty (grading v${GRADING_VERSION}).
 */

import type { PackFile2 } from './packFormat';

export const JOURNEY_PACK_3: PackFile2 = {
  v: 2,
  generatorVersion: ${pack.generatorVersion},
  gradingVersion: ${pack.gradingVersion},
  levels: [
${lines}
  ],
};
`;

const path = new URL('../src/data/journeyPack3.ts', import.meta.url);
if (write) {
  writeFileSync(path, out);
  console.log(`wrote src/data/journeyPack3.ts (${levels.length} levels, ${out.length} bytes)`);
} else {
  const { JOURNEY_PACK_3 } = await import('../src/data/journeyPack3');
  if (JSON.stringify(JOURNEY_PACK_3) !== JSON.stringify(pack)) {
    console.error('src/data/journeyPack3.ts differs from what the generator + grader produce now. A shipped level would change.');
    process.exit(1);
  }
  console.log(`${levels.length} pack-3 levels verified and identical to the committed pack`);
}
const bySize = new Map<string, number>();
for (const l of levels) bySize.set(`${l.size}×${l.size} ${l.tier}`, (bySize.get(`${l.size}×${l.size} ${l.tier}`) ?? 0) + 1);
console.log('mix:', [...bySize].sort().map(([s, c]) => `${s}: ${c}`).join(', '));
