/**
 * Builds the frozen Journey launch pack (levels 1–60) from the deterministic generator and verifies every board.
 *
 *   npm run pack:build   → regenerates src/data/levelPack.ts (only needed if the pack definition changes)
 *   npm run pack:check   → verifies the committed pack without writing (also covered by `npm test`)
 *
 * The pack reproduces exactly the boards v1 players already saw for the same level numbers (same seeds, same
 * generator), so progress and resumable boards carry over. Freezing them means a future generator change can
 * never alter a shipped level. Each board must: have n connected regions, satisfy the rules, have exactly one
 * solution (exact solver), and be solvable by the human deduction engine with no guessing.
 */

import { writeFileSync } from 'node:fs';
import { generatePuzzle } from '../src/engine/generator';
import { levelSpec } from '../src/engine/levels';
import { CURATED_LEVELS } from '../src/meta/chapters';
import { decodePack, encodeBoard, verifyBoard, type PackLevel } from '../src/data/packFormat';

const write = process.argv.includes('--write');

const levels: PackLevel[] = [];
let failures = 0;
for (let level = 1; level <= CURATED_LEVELS; level++) {
  const spec = levelSpec(level);
  const p = generatePuzzle({ size: spec.size, seed: spec.seed, difficulty: spec.difficulty });
  const enc = encodeBoard(level, p);
  const problems = verifyBoard(decodePack({ v: 1, generatorVersion: 1, levels: [enc] })[0].puzzle);
  if (problems.length) {
    failures++;
    console.error(`level ${level}: ${problems.join('; ')}`);
  }
  levels.push(enc);
}

if (failures) {
  console.error(`${failures} level(s) failed verification`);
  process.exit(1);
}

const lines = levels.map((l) => `  ${JSON.stringify(l)},`).join('\n');
const out = `/**
 * Journey launch pack: levels 1–${CURATED_LEVELS}, frozen and verified. GENERATED by scripts/build-level-pack.ts — do not edit.
 * Each entry: level, size, difficulty, seed, regions (one digit per cell, row by row), solution ('.' / 'C' / 'D'),
 * givens [row, col, 1=cat|2=dog], and grading metadata (hardest deduction technique, logical steps).
 */

import type { PackFile } from './packFormat';

export const LEVEL_PACK: PackFile = {
  v: 1,
  generatorVersion: 1,
  levels: [
${lines}
  ],
};
`;

if (write) {
  writeFileSync(new URL('../src/data/levelPack.ts', import.meta.url), out);
  console.log(`wrote src/data/levelPack.ts (${levels.length} levels, ${out.length} bytes)`);
} else {
  console.log(`${levels.length} levels verified (dry run; pass --write to regenerate the pack file)`);
}
const bySize = new Map<number, number>();
for (const l of levels) bySize.set(l.size, (bySize.get(l.size) ?? 0) + 1);
console.log('sizes:', [...bySize].map(([s, c]) => `${s}x${s}×${c}`).join(', '));
