/**
 * Builds and checks Journey pack 4: the one-animal levels 1–20 of spec 4 (D35), frozen and verified like the other
 * packs. From level 21 spec 4 plays the two-animal boards already frozen in the launch pack and pack 3.
 *
 *   npm run pack:build   → regenerates src/data/journeyPack4.ts (with the other packs)
 *   npm run pack:check   → regenerates in memory and fails if the committed pack differs or any board fails
 *
 * Every board must have n connected regions, satisfy the one-animal rule, have exactly one solution with no animals
 * given (exact solver), be solvable by the deduction engine with no guessing, and measure exactly the difficulty its
 * slot asks for. Level 1 (the guided first board) must also open with a one-tile color, so its first step is obvious.
 */

import { writeFileSync } from 'node:fs';
import { encodeBoard, verifyBoard, type PackFile2, type PackLevel2 } from '../src/data/packFormat';
import { GRADING_VERSION, profileOf } from '../src/game/grading';
import { SOLO_LEVELS, journeyTargetSolo, pickBoard } from '../src/game/specs';

const write = process.argv.includes('--write');

/** The guided first board needs a one-tile color region to start from. */
function oneTileRegion(regions: number[][]): boolean {
  const count = new Map<number, number>();
  for (const row of regions) for (const g of row) count.set(g, (count.get(g) ?? 0) + 1);
  return [...count.values()].some((n) => n === 1);
}

const levels: PackLevel2[] = [];
let failures = 0;
for (let level = 1; level <= SOLO_LEVELS; level++) {
  const t = journeyTargetSolo(level);
  // Level 1 keeps looking (in the same fixed order) until the first easy board that also starts from a one-tile color.
  let puzzle = pickBoard(t);
  if (level === 1) for (let k = 1; !oneTileRegion(puzzle.regions) && k < 40; k++) puzzle = pickBoard({ ...t, seedKey: `${t.seedKey}~${k}` });
  const prof = profileOf(puzzle);
  const enc: PackLevel2 = { ...encodeBoard(level, puzzle), spec: 4, target: t.tier, tier: prof.tier, score: prof.score };
  const problems = verifyBoard(puzzle);
  if (puzzle.rule !== 'solo') problems.push('not a one-animal board');
  if (puzzle.size !== t.size) problems.push(`size ${puzzle.size}, slot asks ${t.size}`);
  if (enc.target !== enc.tier) problems.push(`asked for ${enc.target}, measured ${enc.tier}`);
  if (puzzle.givens.length) problems.push('one-animal boards start empty');
  if (level === 1 && !oneTileRegion(puzzle.regions)) problems.push('the first board needs a one-tile color');
  if (problems.length) {
    failures++;
    console.error(`level ${level}: ${problems.join('; ')}`);
  }
  levels.push(enc);
}
if (failures) {
  console.error(`${failures} level(s) failed verification`);
  process.exit(1);
}

const pack: PackFile2 = { v: 2, generatorVersion: 1, gradingVersion: GRADING_VERSION, levels };
const lines = levels.map((l) => `    ${JSON.stringify(l)},`).join('\n');
const out = `/**
 * Journey pack 4: the one-animal levels 1–${SOLO_LEVELS} of spec 4 (D35), frozen and verified. GENERATED by
 * scripts/build-journey-pack4.ts — do not edit. 5×5 lessons, then up to 9×9, each picked and labeled by measured
 * difficulty (grading v${GRADING_VERSION}, one-animal scale). No animals are given: the regions alone make each solution unique.
 */

import type { PackFile2 } from './packFormat';

export const JOURNEY_PACK_4: PackFile2 = {
  v: 2,
  generatorVersion: ${pack.generatorVersion},
  gradingVersion: ${pack.gradingVersion},
  levels: [
${lines}
  ],
};
`;

const path = new URL('../src/data/journeyPack4.ts', import.meta.url);
if (write) {
  writeFileSync(path, out);
  console.log(`wrote src/data/journeyPack4.ts (${levels.length} levels, ${out.length} bytes)`);
} else {
  const { JOURNEY_PACK_4 } = await import('../src/data/journeyPack4');
  if (JSON.stringify(JOURNEY_PACK_4) !== JSON.stringify(pack)) {
    console.error('src/data/journeyPack4.ts differs from what the generator + grader produce now. A shipped level would change.');
    process.exit(1);
  }
  console.log(`${levels.length} pack-4 levels verified and identical to the committed pack`);
}
console.log('levels:', levels.map((l) => `${l.level}:${l.size}${l.tier[0]}`).join(' '));
