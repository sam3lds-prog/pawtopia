/**
 * Builds the world map art (src/ui/art/worldMap.data.ts) from Natural Earth land outlines (public domain), via the
 * world-atlas TopoJSON package (ISC). Run once; the output is committed so the app needs none of these packages.
 *
 *   npx tsx scripts/build-world-map.ts
 *
 * Projection: Natural Earth I, fitted to a 1000×520 box, Antarctica trimmed (nothing lives there in Pawtopia), coordinates
 * rounded to whole units and tiny islands dropped, which keeps the path small. `project()` is exported in the data file
 * as plain numbers (scale, translate) so pins can be placed with the same projection at runtime without d3.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import type { FeatureCollection, MultiPolygon, Polygon } from 'geojson';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land) as unknown as FeatureCollection<MultiPolygon | Polygon>;

const W = 1000;
const H = 520;
// Drop Antarctica (all rings south of -60°) before fitting.
const trimmed: FeatureCollection<MultiPolygon> = {
  type: 'FeatureCollection',
  features: land.features.map((f) => {
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
    return { ...f, geometry: { type: 'MultiPolygon', coordinates: polys.filter((p) => Math.max(...p[0].map((pt) => pt[1])) > -60) } };
  }),
};
const projection = geoNaturalEarth1().fitExtent(
  [
    [8, 8],
    [W - 8, H - 8],
  ],
  trimmed,
);
const path = geoPath(projection);

let d = '';
for (const f of trimmed.features)
  for (const poly of f.geometry.coordinates) {
    const p = path({ type: 'Polygon', coordinates: poly });
    if (!p) continue;
    // Skip specks smaller than a few map units.
    const b = path.bounds({ type: 'Polygon', coordinates: poly });
    if ((b[1][0] - b[0][0]) * (b[1][1] - b[0][1]) < 6) continue;
    d += p.replace(/(\d+\.\d+)/g, (m) => String(Math.round(Number(m))));
  }
// Collapse repeated points produced by rounding.
d = d.replace(/L(-?\d+),(-?\d+)(?=L\1,\2)/g, '');

const scale = projection.scale();
const [tx, ty] = projection.translate();
const out = `/**
 * World land outline for the map. GENERATED by scripts/build-world-map.ts from Natural Earth (public domain) via the
 * world-atlas package (ISC). Natural Earth I projection in a ${W}×${H} box; Antarctica trimmed. Do not edit.
 */

export const WORLD_W = ${W};
export const WORLD_H = ${H};
export const WORLD_LAND = ${JSON.stringify(d)};
/** Natural Earth I projection parameters used for the outline (see projectLonLat in worldMap.ts). */
export const WORLD_PROJECTION = { scale: ${scale.toFixed(4)}, tx: ${tx.toFixed(4)}, ty: ${ty.toFixed(4)} };
`;
writeFileSync(new URL('../src/ui/art/worldMap.data.ts', import.meta.url), out);
console.log(`wrote src/ui/art/worldMap.data.ts (${(out.length / 1024).toFixed(1)} KB)`);
console.log('check: Sydney', projection([151.2, -33.9]), 'London', projection([-0.1, 51.5]));
